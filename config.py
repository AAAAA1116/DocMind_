# -*- coding: utf-8 -*-
"""DocMind_ 全局配置

所有可调参数集中在这里，其它模块一律 ``from config import ...``，
不要在业务代码里写散落的常量。

改动注意
--------
``CHUNK_SIZE`` / ``OVERLAP`` 改了以后，**必须重建索引**（旧索引是按老参数切的），
因为向量库只存文本块，不存切分参数，改了参数旧块不会自动重切。
Web 界面左侧有「重建索引」按钮，或调用 ``core.embed_store.reset_index()``。
"""

from __future__ import annotations

import os
from pathlib import Path

#: 版本号。每次功能合并进来时手动 +0.1，界面和 ``python -m config`` 都会显示，
#: 用来确认「跑起来的确实是刚改的那版代码」。
#: 1.1 = 第五阶段重排 + 第六阶段混合检索；1.2 = 第七阶段评测闭环；
#: 1.3 = 修复 splitter 三处缺陷 + 关闭余弦阈值。
DOCMIND_VERSION = "1.3"

# ---------------------------------------------------------------------------
# 路径
# ---------------------------------------------------------------------------
BASE_DIR = Path(__file__).resolve().parent

DATA_DIR = BASE_DIR / "data"                       # 所有本地数据（已被 .gitignore 忽略）
UPLOAD_DIR = DATA_DIR / "uploads"                  # 上传的原始文件
INDEX_DIR = DATA_DIR / "index"                     # ChromaDB 持久化目录
MODEL_CACHE_DIR = DATA_DIR / "models"              # sentence-transformers 模型缓存
LOG_DIR = BASE_DIR / "logs"                        # 问答日志
MANIFEST_PATH = INDEX_DIR / "ingested.json"        # 增量索引用：已入库文件清单

# ---------------------------------------------------------------------------
# 切分参数（第二阶段 splitter.py）
# ---------------------------------------------------------------------------
CHUNK_SIZE = 500        # 每块最大字符数
OVERLAP = 80            # 相邻块重叠字符数

# ---------------------------------------------------------------------------
# 检索参数（第三阶段 core/embed_store.py）
# ---------------------------------------------------------------------------
TOP_K = 3               # 每次检索返回的候选块数量
EMBED_MODEL_NAME = "BAAI/bge-small-zh-v1.5"

#: 相似度阈值。低于它的候选块会被丢弃；若全部低于阈值，直接回复「知识库中未找到相关信息」。
#:
#: .. warning::
#:     **默认关闭（0.0）。** 在调大这个值之前，先看你数据上的实际分数分布。
#:     bge 官方模型卡明确说：「相似度大于 0.5 并不代表两句相似」，
#:     「真正重要的是分数的相对顺序，而不是绝对值」。
#:     实测本机样例文档（运维手册）的正确命中块，余弦相似度集中在 **0.51 ~ 0.56**。
#:
#:     **有评测数据支撑**：在 10 条黄金评测集上，纯向量路径的误拒率
#:     **0.0 → 38%**、**0.6 → 75%**，且忠实度/相关性/召回/精度四项同时下滑。
#:     原来定 0.6 是拍脑袋定的，实测它把一半以上的正常问题都变成了拒答。
#:
#: .. note::
#:     **混合检索或重排开启时本项自动失效**——BM25 的分数、重排的 sigmoid 概率
#:     和余弦相似度不是一个量纲，拿余弦阈值去卡它们等于把这两层的贡献原地作废。
#:     所以这个值只在「纯向量检索」这一条路径上起作用。
#:     设 0.0 或负数 = 不过滤，完全交给排序 + 大模型自己判断资料够不够。
THRESHOLD = 0.0

# ---------------------------------------------------------------------------
# 重排（第五阶段 core/reranker.py）
# ---------------------------------------------------------------------------
#: 是否开启重排。设 0 / False 就退回纯向量检索，行为与 v1.0 一致。
#: 模型加载失败时会自动降级为不重排，不会让整个问答挂掉。
#:
#: 开启前先看这笔账（本机 4 核 CPU 实测，构造了一个「12 条高度同构条款 + 20 条干扰」
#: 的较难语料来压榨重排的价值）::
#:
#:     指标          纯向量    加重排     变化
#:     top-1 命中    11/12     12/12      +1
#:     top-3 命中    12/12     12/12      +0
#:     MRR           0.958     1.000      +0.042
#:     平均耗时      126 ms    13746 ms   +109 倍
#:
#: 结论：重排确实能把「已经召回到候选里、但排序靠后」的正确答案顶到第一位，
#: 精度收益是真的，但**时间代价这台机器付不起**。有 GPU 时开；
#: 纯 CPU 且在意响应速度时，建议关掉——关掉后排序质量只略降，体验差一个量级。
RERANK_ENABLED = True

#: 重排模型。填仓库名即可；core/reranker.py 会先找 ``data/models/<名字最后一段>``，
#: 命中就用本地目录（彻底离线），否则才联网下载。
RERANK_MODEL = "BAAI/bge-reranker-v2-m3"

#: 粗排召回多少个候选送去精排。重排只能排序，召回没进的它救不回来，
#: 所以这个值要明显大于 TOP_K。越大越准，但**耗时近似线性增长**。
#:
#: .. warning::
#:     重排是纯 CPU 上的交叉编码器前向，成本比向量检索高 **2~3 个数量级**。
#:     本机（4 逻辑核 / 无 CUDA）实测：真实块约 112~279 token，重排 3 个候选要 12~44 秒，
#:     9~10 个候选要 48~83 秒；而纯向量检索只要 30~130 毫秒。
#:     机器负载一波动，同一配置能差 3 倍以上，所以这台机器上**别指望能调出毫秒级**。
#:     有 GPU 的话这一段可以忽略，重排会降到亚秒级。
#:     想在弱 CPU 上要响应速度，就把 RERANK_ENABLED 关掉，或者把这个值降到 5。
RERANK_CANDIDATES = 10

#: 单条输入最大 token 数（**是上限，不是目标**；实际长度取「块有多长」和它的小值）。
#: 模型本身支持 8192，但交叉编码器的耗时与序列长度近似成正比，能少给就少给。
#:
#: 实测本模型 tokenizer 的中文压缩比（含首尾特殊符号）::
#:
#:     120 字 →  94 token
#:     250 字 → 190 token
#:     500 字 → 378 token      ← CHUNK_SIZE=500 切出来的块
#:     800 字 → 599 token
#:
#: 生产库里真实块是 112~279 token，所以 512 实际**不会截断任何东西**，留着是安全的上限。
#: 真要提速只能靠调小它，但那等于拿正文换时间（降到 256 会把 500 字的块砍掉三分之一），
#: 除非确认你的文档块都很短，否则别动。
RERANK_MAX_LENGTH = 512

#: 精排批量大小（每批处理多少对 query-文档）。CPU 上 8 比较稳。
RERANK_BATCH_SIZE = 8

#: 重排分数的过滤阈值，作用在 **sigmoid 之后的相关性概率** 上，取值 (0, 1)。
#: 0 表示不过滤，只按顺序取前 TOP_K 个。
#:
#: .. warning::
#:     它和上面的余弦 ``THRESHOLD`` **不是一个量纲**，数值不可互相照搬。
#:     开了重排之后，``THRESHOLD`` 会自动失效（改由本项把关），
#:     否则余弦阈值会把候选全砍光（本项目实测 6 个查询无一达到 0.6）。
RERANK_THRESHOLD = 0.0

# ---------------------------------------------------------------------------
# 混合检索（第六阶段 core/hybrid.py）
# ---------------------------------------------------------------------------
#: 是否开启混合检索：向量召回 + BM25 词面召回 → RRF 融合。
#:
#: 关掉就退回「只用向量召回」，也就是第五阶段的行为。
#: BM25 的中文分词依赖 jieba；jieba 缺失时 core/hybrid.py 会抛 HybridError，
#: rag_chain 捕获后打印一行提示并**自动退回纯向量**，问答不会因此中断。
#:
#: 两路是互补关系，各管一段：向量管「语义像不像」，BM25 管「字面有没有」。
#: BM25 对**转述/同义改写**（「十三薪」vs「年终双薪」）一样无能为力，
#: 它补的是编号、错误码、型号、英文缩写这类**字面精确匹配**的盲区。
HYBRID_ENABLED = True

#: 每个召回通道各取多少个候选送进 RRF 融合。
#: 两路各取 N 个 → 去重融合（最多 2N 个）→ 再截断到 ``RERANK_CANDIDATES`` 送精排。
HYBRID_PER_SOURCE = 10

#: RRF 的平滑常数 k（原论文取值 60，别动）。
#: 它把头部名次的差距摊平：k 越小越看重「谁排第一」，越大越接近平均。
#: 想调两路的相对影响力，去调下面的权重，不要改这个。
HYBRID_RRF_K = 60

#: 两路在 RRF 里的权重。默认 1.0 / 1.0，表示完全平等。
#:
#: .. note::
#:     **这两个值刻意不调优。** 权重该取多少完全取决于语料构成——
#:     专有名词/编号多就偏 BM25，口语化提问多就偏向向量。
#:     在某一套样例上「调出来」的最优值，换个知识库就不成立，
#:     所以这里留成显式可配的旋钮，交给你按自己的数据定。
HYBRID_VECTOR_WEIGHT = 1.0
HYBRID_BM25_WEIGHT = 1.0

# ---------------------------------------------------------------------------
# 大模型（DeepSeek）
# ---------------------------------------------------------------------------
#: 注意：这里是**对话模型**名，不是 embedding 模型。
#: embedding 模型是上面的 EMBED_MODEL_NAME，两者不要混。
MODEL_NAME = "deepseek-chat"

LLM_BASE_URL = os.environ.get("DEEPSEEK_BASE_URL", "https://api.deepseek.com")
LLM_API_KEY_ENV = "DEEPSEEK_API_KEY"      # 从环境变量 / 项目根 .env 读取
LLM_TIMEOUT = 60.0                         # 单次请求超时（秒）
LLM_MAX_RETRIES = 1                        # 超时后重试次数：1 表示最多请求 2 次
LLM_TEMPERATURE = 0.2                      # 问答场景要稳定，温度调低
LLM_MAX_TOKENS = 1024                      # 单次回答长度上限

#: 模型答不出时的固定话术，与 rag_chain 的 system_prompt 保持一致
REFUSAL_TEXT = "知识库中未找到相关信息"

# ---------------------------------------------------------------------------
# 上传
# ---------------------------------------------------------------------------
#: 允许上传的扩展名，与 loader.py 支持的一致
ALLOWED_EXTENSIONS = (".txt", ".md", ".pdf", ".docx")

# ---------------------------------------------------------------------------
# 日志
# ---------------------------------------------------------------------------
LOG_FILE = LOG_DIR / "qa.log"
LOG_BACKUP_DAYS = 30        # 按天滚动，保留 30 天
LOG_SNIPPET_LEN = 50        # 日志里每条检索片段只记前 50 字

# ---------------------------------------------------------------------------
# 读取 .env（放在最后，保证上面的 os.environ.get 能拿到值之后不会再被覆盖）
# ---------------------------------------------------------------------------
try:
    from dotenv import load_dotenv

    load_dotenv(BASE_DIR / ".env")
except ImportError:      # python-dotenv 未安装时静默跳过，不阻塞启动
    pass


def ensure_dirs() -> None:
    """创建运行所需目录。启动时调一次即可，重复调用无害。"""
    for d in (DATA_DIR, UPLOAD_DIR, INDEX_DIR, MODEL_CACHE_DIR, LOG_DIR):
        d.mkdir(parents=True, exist_ok=True)


def summary() -> str:
    """配置摘要，启动时打印一份，方便确认参数是否生效。"""
    lines = [
        "=" * 68,
        f"DocMind_ 配置　（v{DOCMIND_VERSION}）",
        "=" * 68,
        f"  切分        CHUNK_SIZE={CHUNK_SIZE}  OVERLAP={OVERLAP}",
        f"  检索        TOP_K={TOP_K}  THRESHOLD={THRESHOLD}",
        f"  embedding   {EMBED_MODEL_NAME}",
        (
            f"  混合检索    开启  向量 + BM25 → RRF(k={HYBRID_RRF_K})"
            f"  各取 {HYBRID_PER_SOURCE} 个  权重 {HYBRID_VECTOR_WEIGHT}/{HYBRID_BM25_WEIGHT}"
            if HYBRID_ENABLED
            else "  混合检索    关闭（只用向量召回）"
        ),
        (
            f"  重排        {'开启' if RERANK_ENABLED else '关闭'}"
            f"  召回 {RERANK_CANDIDATES} → 精选 {TOP_K}"
            f"  阈值 {RERANK_THRESHOLD}"
            if RERANK_ENABLED
            else f"  重排        关闭（纯向量检索）"
        ),
        f"  重排模型    {RERANK_MODEL}  max_length={RERANK_MAX_LENGTH}  batch={RERANK_BATCH_SIZE}",
        f"  对话模型    {MODEL_NAME}  ({LLM_BASE_URL})",
        f"  API Key     {'已设置' if os.environ.get(LLM_API_KEY_ENV) else '未设置（.env 里填 ' + LLM_API_KEY_ENV + '）'}",
        f"  索引目录    {INDEX_DIR}",
        f"  日志文件    {LOG_FILE}",
        "=" * 68,
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    ensure_dirs()
    print(summary())
