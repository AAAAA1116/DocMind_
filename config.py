def _hybrid_lines() -> list:
    """混合检索那一行。打印的是**真实生效的召回深度**，不是 ``HYBRID_PER_SOURCE``。

    为什么不能直接打印 ``HYBRID_PER_SOURCE``：``hybrid_search`` 内部算的是
    ``depth = max(HYBRID_PER_SOURCE, k)``，而 ``rag_chain`` 传进去的 ``k`` 是
    ``max(RERANK_CANDIDATES, TOP_K)``。两个 max 叠起来，真实深度是三者取最大。

    实际踩过的坑：v1.8 之前这里打印「各取 10 个」，而每路实际取 100 —— **摘要说了假话**，
    会让人误以为调 ``HYBRID_PER_SOURCE`` 有效（真去调，看不到任何变化）。
    这里只修显示，不碰任何检索参数。
    """
    if not HYBRID_ENABLED:
        return ["  混合检索    关闭（只用向量召回）"]

    depth = max(HYBRID_PER_SOURCE, RERANK_CANDIDATES, TOP_K)
    lines = [
        f"  混合检索    开启  向量 + BM25 → RRF(k={HYBRID_RRF_K})"
        f"  各取 {depth} 个  权重 {HYBRID_VECTOR_WEIGHT}/{HYBRID_BM25_WEIGHT}"
    ]
    if depth != HYBRID_PER_SOURCE:
        lines.append(
            f"              深度由候选池决定：HYBRID_PER_SOURCE={HYBRID_PER_SOURCE}"
            f" 被 max 到 {depth}（改它当前无效果）"
        )
    return lines


def _rerank_lines() -> list:
    """精排那两行。API 后端要多带一个「key 有没有配」的状态 —— 那是它最常见的故障点。"""
    if not RERANK_ENABLED:
        tail = (
            f"候选按 RRF 名次直接取前 {TOP_K} 个"
            if HYBRID_ENABLED
            else "纯向量检索"
        )
        return [f"  重排        关闭（不精排，{tail}）"]

    # 后端详情的唯一来源是 core.reranker 的 API_PROVIDERS 表；这里懒导入，
    # 避免 config → core.reranker → config 的循环导入。读不到就退回裸配置值。
    try:
        from core.reranker import provider_info

        info = provider_info()
        if info["is_local"]:
            head = f"  重排        开启  后端 本地交叉编码器（{info['model']}）"
        else:
            head = (
                f"  重排        开启  后端 {info['name']}（{info['model']}）"
                f"   key {'已设置' if info['key_set'] else '未设置 → .env 里填 ' + info['key_env']}"
            )
            if not info["key_set"]:
                head += "　（精排会自动降级为不精排）"
    except Exception as e:  # noqa: BLE001
        head = f"  重排        开启  后端 {RERANK_PROVIDER}（详情读取失败：{type(e).__name__}）"

    return [
        head,
        f"              池 {RERANK_CANDIDATES} → 精选 {TOP_K}   阈值 {RERANK_THRESHOLD}",
    ]


def summary() -> str:
    """配置摘要，启动时打印一份，方便确认参数是否生效。"""
    lines = [
        "=" * 68,
        f"DocMind_ 配置　（v{DOCMIND_VERSION}）",
        "=" * 68,
        f"  切分        结构优先（第X条 / 第X章）  上限 {CHUNK_SIZE} 字",
        f"              定长兜底 OVERLAP={OVERLAP}（无条款结构的文档才走）",
        f"  检索        TOP_K={TOP_K}  THRESHOLD={THRESHOLD}",
        f"  embedding   {EMBED_MODEL_NAME}",
        *_hybrid_lines(),
        *_rerank_lines(),
        f"  对话模型    {MODEL_NAME}  ({LLM_BASE_URL})",
        f"  API Key     {'已设置' if os.environ.get(LLM_API_KEY_ENV) else '未设置（.env 里填 ' + LLM_API_KEY_ENV + '）'}",
        f"  索引目录    {INDEX_DIR}",
        f"  日志文件    {LOG_FILE}",
        "=" * 68,
    ]
    return "\n".join(lines)


