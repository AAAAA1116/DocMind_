# ---------------------------------------------------------------------------
# 切分参数（第二阶段 splitter.py）
# ---------------------------------------------------------------------------
#: 每块最大字符数。**这是上限，不是目标** —— 走结构切分时块长由条款边界决定
#: （见 ``splitter.split_by_structure``），不会被主动撑到接近本值；
#: 只有"文档没有条款结构"退回定长切分时，块长才会贴着它。
#:
#: 取 480 而不是 500 是 token 实测的结果，不是随手取整：
#: ``bge-small-zh-v1.5`` 上限 512 token，本项目 7 份制度语料实测压缩比约
#: **0.956 token/字**（500 字 ≈ 478 token，已占 93%；520 字 ≈ 497 token；
#: 560 字 → 535 token 越界）。扣掉 10% 余量 → 480 字 ≈ 459 token。
#:
#: .. warning::
#:     越界是**静默截断** —— 超出 512 token 的部分根本不进向量，检索时等于隐形。
#:     它不报错、不打日志，只表现为"这段内容怎么都搜不到"。
#:     **数字 / 英文更密的语料（年报、财报）压缩比更高，换语料后要重新实测。**
#:     实测代价：480 相对 500 只多 5.5% 的块，索引总字数几乎不变。
CHUNK_SIZE = 480

#: 相邻块重叠字符数。**只对定长切分路径生效** ——
#: 结构切分不使用重叠：切点已经落在条款边界上，重叠的内容纯属冗余，
#: 它和正确答案抢 TOP_K 名额，还把索引撑大 20%（实测 1.15x → 0.96x 展开率）。
#: 也就是说，语料换成条款体文档后，这个值实际上不再起作用。
OVERLAP = 80

# ---------------------------------------------------------------------------
# 检索参数（第三阶段 core/embed_store.py）
# ---------------------------------------------------------------------------
#: 每次检索返回、交给大模型作答的候选块数量。
#:
#: 实测依据（30 条真实制度语料评测集，27 条正例，答案要点覆盖率）::
#:
#:     K=3 → 0.81     K=5 → 0.88     K=8 → 0.93     K=12 以上饱和（边际 <0.03）
#:
#: 失败模式高度一致：**答案分散在相隔很远的两条条款里，K=3 覆盖不全**，
#: 模型于是只答一半、或者老实拒答（它拒答是对的，错在没把答案喂给它）。
#: q08（内控五项目标）、q19（会计档案保存期限）在 K=3 时拒答，K=8 时完整答对，
#: 这两条就是上一轮「只开混合检索」那个配置 11% 误拒率的全部来源。
#: **这是「喂几块」的问题，不是排序问题——调阈值、换重排模型都救不回来。**
#:
#: .. note::
#:     **1.8 起取 12，是配合精排池 100 的实测结果，不是随手加的。**
#:
#:     18 条 Golden Set 上，池 100 + 精排 + K=8 只有 16/18（q06 差一个数字，
#:     它的回答块排在第 10 名）；K=12 才拿到 17/18。因为精排后的第 9~12 名
#:     仍然可能是答案，而前 8 名的坑位会被「同一份文档里的相似条款」占掉。
#:
#:     调这个值仍然几乎零成本：候选池深度取 ``max(RERANK_CANDIDATES, TOP_K)``，
#:     现在 RERANK_CANDIDATES=100 远大于它，**改成 12 或 8 都是同一批 100 个候选**，
#:     送达 API 的 token 数、检索次数、精排次数全部不变。
#:     唯一代价是塞进 prompt 的文本从约 4000 字涨到约 6000 字（输入 token + 一点延迟）。
TOP_K = 12
EMBED_MODEL_NAME = "BAAI/bge-small-zh-v1.5"

#: 相似度阈值。低于它的候选块会被丢弃；若全部低于阈值，直接回复「知识库中未找到相关信息」。
#:
#: .. warning::
#:     **默认关闭（0.0）。** 在调大这个值之前，先看你数据上的实际分数分布。
#:     bge 官方模型卡明确说：「相似度大于 0.5 并不代表两句相似」，
#:     「真正重要的是分数的相对顺序，而不是绝对值」。
#:     实测本机样例文档（运维手册）的正确命中块，余弦相似度集中在 **0.51 ~ 0.56**。
#:
#:     **有评测数据支撑**：在 10 条黄金评测集上，纯向量路径的误拒率
#:     **0.0 → 38%**、**0.6 → 75%**，且忠实度/相关性/召回/精度四项同时下滑。
#:     原来定 0.6 是拍脑袋定的，实测它把一半以上的正常问题都变成了拒答。
#:
#: .. note::
#:     **混合检索或重排开启时本项自动失效**——BM25 的分数、重排的 sigmoid 概率
#:     和余弦相似度不是一个量纲，拿余弦阈值去卡它们等于把这两层的贡献原地作废。
#:     所以这个值只在「纯向量检索」这一条路径上起作用。
#:     设 0.0 或负数 = 不过滤，完全交给排序 + 大模型自己判断资料够不够。
THRESHOLD = 0.0

# ---------------------------------------------------------------------------
# 重排（第五阶段 core/reranker.py）
# ---------------------------------------------------------------------------
#: 是否开启重排。**1.8 起默认开启**（后端换成托管 API，见下面的 ``RERANK_PROVIDER``）。
#: 关掉即退回「按 RRF 名次直接取前 TOP_K 个」，代码与降级逻辑完整保留。
#: 精排调用失败（网络 / 额度 / 鉴权）会自动降级为不精排，**不会让整个问答挂掉**。
#:
#: 为什么 1.4~1.7 一直关着、1.8 才开 —— 1.4 那次实测的结论是「精排不值」::
#:
#:     配置                   忠实度   相关性    召回     精度    误拒率    平均耗时
#:     混合 K=8（无精排）      0.9423  0.9031  0.8519  0.5804     0%     1,560 ms
#:     混合 K=3 + 本地精排     0.9669  0.8869  0.8642  0.9105     4%    35,672 ms
#:
#: 那个结论本身没错，但它证明的是「**本地**精排在这台机器上不可用」，
#: 不是「精排没用」。本机 8GB 内存装不下 XLM-R-large（FP32 权重 2.3GB），
#: 跑 100 个候选时内存爆掉、系统换页，实测 344 秒/问，而且跑第二个问题就把机器拖死。
#: **这是资源问题，不是算法问题。**
#:
#: 换托管 API 之后同一套算法变成 **约 2 秒/问**（快 170 倍、零内存占用），
#: 「精排把答案从第 10 名提到第 3」这种收益第一次变得值得。
#: 18 条 Golden Set 实测：**16/18 → 17/18**，q06 由 FAIL 转 PASS，其余 17 条零退化。
RERANK_ENABLED = True

#: 精排后端。三选一：
#:
#:   ``"local"``        本地交叉编码器（要 2.3GB 内存 + CPU 前向，弱机不可用）
#:   ``"siliconflow"``  硅基流动托管 API，模型 ``BAAI/bge-reranker-v2-m3``（该平台免费模型）
#:   ``"dashscope"``    阿里云百炼托管 API，模型 ``gte-rerank-v2``
#:
#: API 后端的端点 / 返回结构 / key 所在的环境变量，统一由 ``core/reranker.py``
#: 的 ``API_PROVIDERS`` 表定义 —— 两家返回结构不同（硅基流动是顶层 ``results``，
#: 百炼是 ``output.results``），**不是换个 URL 就能互换的**。
#:
#: .. warning::
#:     托管服务是**别人的账户**，会因欠费 / 额度耗尽 / 限流整体停摆。
#:     实测：阿里云百炼账户欠费时，rerank 与所有 qwen 模型一起返回
#:     ``HTTP 400 Arrearage``，18 条回归**全灭** —— 那个 0/18 是假成绩，
#:     只代表「没让进门」，不代表方案效果。
#:     所以 ``"local"`` 必须始终是一条能走通的路（代码完整保留，只是慢）。
RERANK_PROVIDER = "siliconflow"

#: **仅本地后端**（``RERANK_PROVIDER="local"``）使用：重排模型名。
#: 填仓库名即可；core/reranker.py 会先找 ``data/models/<名字最后一段>``，
#: 命中就用本地目录（彻底离线），否则才联网下载。
RERANK_MODEL = "BAAI/bge-reranker-v2-m3"

#: **仅 API 后端**使用：覆盖该后端的默认模型名。留空 = 用 ``API_PROVIDERS`` 表里的默认值。
#: 需要换模型（硅基流动上更高配的 reranker，或百炼的其它版本）时才填。
RERANK_API_MODEL = ""

#: **仅 API 后端**使用：单次请求超时（秒）。
#: 100 个候选实测 1.1~2.0 秒，60 秒是给网络抖动留的余量，不是正常耗时。
RERANK_API_TIMEOUT = 60.0

#: 粗排召回多少个候选送去精排。重排只能排序、不能召回，池子必须明显大于 TOP_K。
#:
#: .. important::
#:     **1.8 取 100，是 API 后端实测的甜点 —— 不是越大越好。**
#:
#:     池子变大时，答案块的名次反而会**后退**：多出来的候选里哪怕只有几块稍微沾边，
#:     也会挤在答案块前面。18 条 Golden Set 里 q06 的三个答案块实测::
#:
#:         池 100  → 精排名次 #3 / #7 / #10  → TOP_K=12 时 3/3 全中 ✅
#:         池 200  → 名次后退（新宝滑到 #12，刚好卡线）
#:         池 300  → 新宝掉到 #13            → TOP_K=12 时只剩 2/3
#:
#:     甜点是 **池 100~200 + TOP_K 12**。注意这个性质跟纯向量召回**不同**：
#:     召回任务的池子大是纯赚（多召回多机会），**排序任务的池子大要重新权衡**
#:     （机会和竞争者一起增加）。这是召回与排序的分水岭。
#:
#: .. warning::
#:     **切回 ``RERANK_PROVIDER="local"`` 时必须先把这个值降到 30 以下。**
#:     本地后端在 8GB 机器上跑 100 个候选会爆内存 → 系统换页 → 表现成「卡死」
#:     （实测卡死 2 小时 19 分，日志连着 132 分钟没有动静）。
#:     本地 CPU 的耗时也近似线性：池 50 约 177 秒，池 100 约 344 秒。
RERANK_CANDIDATES = 100

#: **仅本地后端**使用：单条输入最大 token 数（**是上限，不是目标**；
#: 实际长度取「块有多长」和它的小值）。
#: 模型本身支持 8192，但交叉编码器的耗时与序列长度近似成正比，能少给就少给。
#:
#: .. note::
#:     **API 后端用不到这一项** —— 长度由服务端自己截。下面这组数字保持原样未改，
#:     因为它们对应的是本地 XLM-R tokenizer，跟 API 侧的行为没有关系。
#:
#: 历史注释（参考，来源未考；与 CHUNK_SIZE 处 ``bge-small-zh-v1.5`` 的实测压缩比
#: 0.956 token/字对不上，那很正常——两者不是同一个 tokenizer，数值不可互相照搬）::
#:
#:     120 字 →  94 token
#:     250 字 → 190 token
#:     500 字 → 378 token
#:     800 字 → 599 token
#:
#: 结构切分后真实块长 p50≈390、max=CHUNK_SIZE，所以 512 仍然不会截断。
#: 真要提速只能靠调小它，但那等于拿正文换时间（降到 256 会把 480 字的块砍掉一半）。
RERANK_MAX_LENGTH = 512

#: **仅本地后端**使用：精排批量大小（每批处理多少对 query-文档）。CPU 上 8 比较稳。
RERANK_BATCH_SIZE = 8

#: 重排分数的过滤阈值，作用在 **sigmoid 之后的相关性概率** 上，取值 (0, 1)。
#: 0 表示不过滤，只按顺序取前 TOP_K 个。
#:
#: .. warning::
#:     它和上面的余弦 ``THRESHOLD`` **不是一个量纲**，数值不可互相照搬。
#:     开了重排之后，``THRESHOLD`` 会自动失效（改由本项把关），
#:     否则余弦阈值会把候选全砍光（本项目实测 6 个查询无一达到 0.6）。
RERANK_THRESHOLD = 0.0

# ---------------------------------------------------------------------------
# 混合检索（第六阶段 core/hybrid.py）
# ---------------------------------------------------------------------------
#: 是否开启混合检索：向量召回 + BM25 词面召回 → RRF 融合。
#:
#: 关掉就退回「只用向量召回」，也就是第五阶段的行为。
#: BM25 的中文分词依赖 jieba；jieba 缺失时 core/hybrid.py 会抛 HybridError，
#: rag_chain 捕获后打印一行提示并**自动退回纯向量**，问答不会因此中断。
#:
#: 两路是互补关系，各管一段：向量管「语义像不像」，BM25 管「字面有没有」。
#: BM25 对**转述/同义改写**（「十三薪」vs「年终双薪」）一样无能为力，
#: 它补的是编号、错误码、型号、英文缩写这类**字面精确匹配**的盲区。
HYBRID_ENABLED = True

#: 每个召回通道各取多少个候选送进 RRF 融合。
#: 两路各取 N 个 → 去重融合（最多 2N 个）→ 再截断到 ``RERANK_CANDIDATES`` 送精排。
#:
#: .. warning::
#:     **精排开启时这一项实际上不起作用。**
#:     ``hybrid_search`` 的真实召回深度是 ``max(HYBRID_PER_SOURCE, k)``，
#:     而 rag_chain 传进去的 ``k`` 是 ``max(RERANK_CANDIDATES, TOP_K)`` = 100。
#:     100 > 10，所以两路各取 100 个 —— **改这里看不到任何变化**。
#:     （踩过：诊断 q06 时以为调它能加深召回，白测了好几轮。）
#:     只有在「不开精排」的路径上，它才重新回到主导地位。
HYBRID_PER_SOURCE = 10

#: RRF 的平滑常数 k（原论文取值 60，别动）。
#: 它把头部名次的差距摊平：k 越小越看重「谁排第一」，越大越接近平均。
#: 想调两路的相对影响力，去调下面的权重，不要改这个。
HYBRID_RRF_K = 60

#: 两路在 RRF 里的权重。默认 1.0 / 1.0，表示完全平等。
#:
#: .. note::
#:     **这两个值刻意不调优。** 权重该取多少完全取决于语料构成——
#:     专有名词/编号多就偏 BM25，口语化提问多就偏向向量。
#:     在某一套样例上「调出来」的最优值，换个知识库就不成立，
#:     所以这里留成显式可配的旋钮，交给你按自己的数据定。
HYBRID_VECTOR_WEIGHT = 1.0
HYBRID_BM25_WEIGHT = 1.0

